// TestChannelRender_Deterministic guards status's byte comparison:
// rendering the same input twice yields the same bytes.
func TestChannelRender_Deterministic(t *testing.T) {
	entries := channelFixture(t)
	b := Budget{Cap: Cap{Limit: 120, Unit: CapUTF16}}
	first, err := renderChannel(FormatCursorMDC, entries, Frame{Banner: localBanner}, b)
	if err != nil {
		t.Fatalf("renderChannel: %v", err)
	}
	second, err := renderChannel(FormatCursorMDC, entries, Frame{Banner: localBanner}, b)
	if err != nil {
		t.Fatalf("renderChannel: %v", err)
	}
	if !reflect.DeepEqual(first, second) {
		t.Errorf("two renders differ:\n%q\n%q", first.Bytes, second.Bytes)
	}
}

