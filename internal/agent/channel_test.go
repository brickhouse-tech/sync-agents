// TestChannelBudgetSourcesResolve calls every row's BudgetSource with an
// empty environment, so a row cannot reference a resolver that fails on
// a machine without the tool's config.
func TestChannelBudgetSourcesResolve(t *testing.T) {
	tc := ToolContext{Parent: "/home/u", Home: "/home/u/.codex", Env: mapEnv(nil, nil)}
	for id, rows := range channelSpecs {
		for scope, spec := range rows {
			if spec.Budget == nil {
				continue
			}
			b, err := spec.Budget(tc)
			if err != nil {
				t.Errorf("%s/%s: %v", id, scope, err)
			}
			if b.Cap.Limit <= 0 {
				t.Errorf("%s/%s: limit %d", id, scope, b.Cap.Limit)
			}
		}
	}
}
