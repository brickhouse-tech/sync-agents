// channelFixture writes three rules (one OS-scoped) under a temp
// .agents/ and returns them as sorted entries, the shape passiveEntries
// produces.
func channelFixture(t *testing.T) []Entry {
	t.Helper()
	tree := filepath.Join(t.TempDir(), ".agents")
	brew := writeArtifact(t, tree, "rules/macos/brew.md", "Use brew.\n")
	sec := writeArtifact(t, tree, "rules/security.md", "---\ndescription: Never leak secrets\n---\nNever commit secrets.\n")
	tst := writeArtifact(t, tree, "rules/testing.md", "Write tests.\n")
	return []Entry{
		{Name: "macos/brew", Source: brew, Display: ".agents/rules/macos/brew.md"},
		{Name: "security", Source: sec, Display: ".agents/rules/security.md", Description: "Never leak secrets"},
		{Name: "testing", Source: tst, Display: ".agents/rules/testing.md"},
	}
}

// channelFixtureBody is what the fixture's three sections render to.
const channelFixtureBody = "<!-- OS: macos -->\n## macos/brew\n\nUse brew.\n\n" +
	"## security\n\nNever commit secrets.\n\n" +
	"## testing\n\nWrite tests.\n\n"

// TestChannelRender_FormatGoldens pins every format's exact bytes:
// frontmatter dialect, the AGENTS.md copy for the Codex override, the
// banner, OS headers, and one trailing newline.
func TestChannelRender_FormatGoldens(t *testing.T) {
	entries := channelFixture(t)
	agentsMD := "# AGENTS.md\n\nUse pnpm.\n\n" +
		"<!-- sync-agents:openclaw-rules:start -->\n## gateway\nbody\n<!-- sync-agents:openclaw-rules:end -->\n"

	cases := []struct {
		name   string
		format Format
		frame  Frame
		want   string
	}{
		{
			name:   "markdown",
			format: FormatMarkdown,
			frame:  Frame{Banner: localBanner},
			want:   localBanner + "\n\n" + channelFixtureBody,
		},
		{
			name:   "cursor mdc",
			format: FormatCursorMDC,
			frame:  Frame{Banner: localBanner},
			want: "---\ndescription: Shared rules from .agents/ (generated by sync-agents)\nalwaysApply: true\n---\n" +
				localBanner + "\n\n" + channelFixtureBody,
		},
		{
			name:   "copilot instructions",
			format: FormatCopilotInstructions,
			frame:  Frame{Banner: globalBanner},
			want:   "---\napplyTo: \"**\"\n---\n" + globalBanner + "\n\n" + channelFixtureBody,
		},
		{
			name:   "codex override strips regions from the AGENTS.md copy",
			format: FormatCodexOverride,
			frame:  Frame{Banner: localBanner, AgentsMD: []byte(agentsMD)},
			want: "# AGENTS.md\n\nUse pnpm.\n\n" + codexOverrideNote + "\n" +
				localBanner + "\n\n" + channelFixtureBody,
		},
		{
			name:   "codex override without AGENTS.md has no copy and no note",
			format: FormatCodexOverride,
			frame:  Frame{Banner: localBanner},
			want:   localBanner + "\n\n" + channelFixtureBody,
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			r, err := renderChannel(tc.format, entries, tc.frame, Budget{})
			if err != nil {
				t.Fatalf("renderChannel: %v", err)
			}
			if got := string(r.Bytes); got != tc.want {
				t.Errorf("bytes mismatch\n--- got ---\n%s\n--- want ---\n%s", got, tc.want)
			}
			if want := []string{"macos/brew", "security", "testing"}; !reflect.DeepEqual(r.Inlined, want) || r.Pointers != nil {
				t.Errorf("inlined=%v pointers=%v, want all inlined", r.Inlined, r.Pointers)
			}
		})
	}
}

