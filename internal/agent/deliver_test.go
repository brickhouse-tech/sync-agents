// TestDeliver_SecondSyncWritesNothing: a converged project is a no-op.
// Every file keeps its mtime and sync reports nothing it changed.
func TestDeliver_SecondSyncWritesNothing(t *testing.T) {
	app, root, buf := newDeliverApp(t, allChannelTargets...)
	if err := app.CmdSync(); err != nil {
		t.Fatalf("first sync: %v\n%s", err, buf)
	}
	mtimes := func() map[string]time.Time {
		m := map[string]time.Time{}
		filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
			if fi, err := os.Lstat(p); err == nil {
				m[p] = fi.ModTime()
			}
			return nil
		})
		return m
	}
	before := mtimes()
	buf.Reset()
	if err := app.CmdSync(); err != nil {
		t.Fatalf("second sync: %v\n%s", err, buf)
	}
	if after := mtimes(); !reflect.DeepEqual(before, after) {
		for p, ts := range after {
			if !before[p].Equal(ts) {
				t.Errorf("second sync touched %s", p)
			}
		}
	}
	for _, noise := range []string{"Regenerated", "Linked:", "Repaired:", "Created", "Added"} {
		if strings.Contains(buf.String(), noise) {
			t.Errorf("second sync reported %q:\n%s", noise, buf)
		}
	}
}

// TestDeliver_CleanRestoresPreSyncTree: clean removes every link, the
// index, the created opencode.json, and the directories they needed.
// .gitignore lines are kept, as they always were.
func TestDeliver_CleanRestoresPreSyncTree(t *testing.T) {
	app, root, buf := newDeliverApp(t, allChannelTargets...)
	before := treeSnapshot(t, root)
	if err := app.CmdSync(); err != nil {
		t.Fatalf("CmdSync: %v\n%s", err, buf)
	}
	if err := app.CmdClean(); err != nil {
		t.Fatalf("CmdClean: %v\n%s", err, buf)
	}
	after := treeSnapshot(t, root)
	delete(after, ".gitignore")
	if !reflect.DeepEqual(before, after) {
		var diff []string
		for p, v := range after {
			if before[p] != v {
				diff = append(diff, "+ "+p)
			}
		}
		for p := range before {
			if _, ok := after[p]; !ok {
				diff = append(diff, "- "+p)
			}
		}
		sort.Strings(diff)
		t.Errorf("clean left the tree changed:\n%s\n%s", strings.Join(diff, "\n"), buf)
	}
}

