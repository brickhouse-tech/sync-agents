// treeSnapshot maps every path under root (except .git) to its
// content, or "-> target" for a symlink, or "/" for a directory.
func treeSnapshot(t *testing.T, root string) map[string]string {
	t.Helper()
	snap := map[string]string{}
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, p)
		if rel == "." {
			return nil
		}
		if rel == ".git" {
			return filepath.SkipDir
		}
		switch {
		case d.Type()&fs.ModeSymlink != 0:
			target, _ := os.Readlink(p)
			snap[rel] = "-> " + target
		case d.IsDir():
			snap[rel] = "/"
		default:
			data, _ := os.ReadFile(p)
			snap[rel] = string(data)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return snap
}

// links returns every symlink under root outside .agents/, as
// path -> link text.
func links(t *testing.T, root string) map[string]string {
	t.Helper()
	out := map[string]string{}
	for p, v := range treeSnapshot(t, root) {
		if strings.HasPrefix(v, "-> ") && !strings.HasPrefix(p, ".agents"+string(filepath.Separator)) {
			out[filepath.ToSlash(p)] = strings.TrimPrefix(v, "-> ")
		}
	}
	return out
}

