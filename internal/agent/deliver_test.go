func TestReadConfigIndex(t *testing.T) {
	dir := t.TempDir()
	if p, err := ReadConfigIndex(dir); p != IndexLocal || err != nil {
		t.Errorf("absent config: %v %v", p, err)
	}
	for val, want := range map[string]IndexPolicy{"commit": IndexCommit, "local": IndexLocal, "COMMIT": IndexCommit} {
		writeFile(t, filepath.Join(dir, "config"), "# index = commit\nindex = "+val+"\n")
		if p, err := ReadConfigIndex(dir); p != want || err != nil {
			t.Errorf("%s: %v %v", val, p, err)
		}
	}
	writeFile(t, filepath.Join(dir, "config"), "index = maybe\n")
	if p, err := ReadConfigIndex(dir); p != IndexLocal || err == nil {
		t.Errorf("typo must fall back to local with an error: %v %v", p, err)
	}
}

// TestCmdHook_ReplacesOldBlock: re-running the hook command upgrades
// the pre-SPEC-013 block in place and keeps the user's lines; a third
// run changes nothing.
func TestCmdHook_ReplacesOldBlock(t *testing.T) {
	root := t.TempDir()
	hook := filepath.Join(root, ".git", "hooks", "pre-commit")
	old := "#!/bin/sh\necho before\n\n# --- sync-agents start ---\nif command -v sync-agents >/dev/null 2>&1; then\n" +
		"  sync-agents sync 2>/dev/null\n  sync-agents index 2>/dev/null\n" +
		"  git add AGENTS.md CLAUDE.md .claude/ .windsurf/ .cursor/ .github/copilot/ 2>/dev/null || true\nfi\n" +
		"# --- sync-agents end ---\necho after\n"
	writeFile(t, hook, old)
	var buf bytes.Buffer
	app := &App{ProjectRoot: root, Stdout: &buf, Stderr: &buf}
	if err := app.CmdHook(); err != nil {
		t.Fatal(err)
	}
	want := "#!/bin/sh\necho before\n\n" + hookBlock + "echo after\n"
	assertContent(t, hook, want)
	if err := app.CmdHook(); err != nil {
		t.Fatal(err)
	}
	assertContent(t, hook, want)
	if !strings.Contains(buf.String(), "already installed") {
		t.Errorf("second run should be a no-op:\n%s", buf.String())
	}
	if strings.Contains(want, "AGENTS.md") || strings.Contains(want, "CLAUDE.md") {
		t.Error("the hook must not git-add files that may not exist")
	}
}
