// newDeliverApp builds a project with two rules and a skill, a
// user-owned AGENTS.md, and a separate global root holding one rule of
// its own and one the project overrides. The global root's parent
// stands in for $HOME (Codex budget lookups stay inside it).
func newDeliverApp(t *testing.T, targets ...string) (*App, string, *bytes.Buffer) {
	t.Helper()
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "AGENTS.md"), deliverAgentsMD)
	writeFile(t, filepath.Join(root, ".agents", "rules", "security.md"), "---\ndescription: Never leak secrets\n---\nNever commit secrets.\n")
	writeFile(t, filepath.Join(root, ".agents", "rules", "testing.md"), "Write tests.\n")
	writeFile(t, filepath.Join(root, ".agents", "skills", "deploy", "SKILL.md"), "---\nname: deploy\ndescription: Deploy it\n---\nRun deploy.\n")
	global := filepath.Join(t.TempDir(), ".agents")
	writeFile(t, filepath.Join(global, "rules", "global-only.md"), "Global rule.\n")
	writeFile(t, filepath.Join(global, "rules", "security.md"), "Global security, overridden.\n")
	var buf bytes.Buffer
	app := &App{
		ProjectRoot:   root,
		GlobalRoot:    global,
		ActiveTargets: targets,
		Stdout:        &buf,
		Stderr:        &buf,
	}
	return app, root, &buf
}

