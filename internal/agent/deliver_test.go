// TestDeliver_OpencodeConsent: an existing opencode.json is the
// user's. Config targets do not edit it; one --targets run does, and
// later runs keep the entry.
func TestDeliver_OpencodeConsent(t *testing.T) {
	app, root, buf := newDeliverApp(t, "opencode")
	cfg := filepath.Join(root, "opencode.json")
	const mine = "{\n  \"$schema\": \"https://opencode.ai/config.json\"\n}\n"
	writeFile(t, cfg, mine)

	res, err := app.deliverChannels(ChannelRun{Scope: ScopeLocal, Mode: ChannelMount})
	if err != nil || len(res) != 1 || res[0].State != ChannelUnmounted {
		t.Fatalf("without consent: %+v %v", res, err)
	}
	if !strings.Contains(res[0].Detail, "--targets opencode") {
		t.Errorf("detail does not name the consent command: %q", res[0].Detail)
	}
	assertContent(t, cfg, mine)

	app.TargetsFromFlag = true
	res, err = app.deliverChannels(ChannelRun{Scope: ScopeLocal, Mode: ChannelMount, Explicit: app.explicitTargets()})
	if err != nil || res[0].State != ChannelSynced {
		t.Fatalf("with consent: %+v %v\n%s", res, err, buf)
	}
	assertContent(t, cfg, "{\n  \"$schema\": \"https://opencode.ai/config.json\",\n  \"instructions\": [\".agents/index/opencode.md\"]\n}\n")

	app.TargetsFromFlag = false
	res, _ = app.deliverChannels(ChannelRun{Scope: ScopeLocal, Mode: ChannelMount})
	if res[0].State != ChannelSynced {
		t.Errorf("an entry that carries ours must stay synced: %+v", res)
	}

	if _, err := app.cleanChannels(ScopeLocal, nil); err != nil {
		t.Fatal(err)
	}
	assertContent(t, cfg, mine)
}

