	assertAbsent(t, filepath.Join(root, ".github", "copilot", "rules", "security.md"))
	assertContent(t, filepath.Join(root, ".github", "copilot", "rules", "team.md"), "team")
	if fi, err := os.Lstat(filepath.Join(root, ".opencode", "rules")); err != nil || fi.Mode()&os.ModeSymlink == 0 {
		t.Error("a symlink outside .agents/ must be left alone")
	}
